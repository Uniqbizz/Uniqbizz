                                    Buddhist crowd from all over the world.
                                </p>
                                <p class="pera">
                                    Ladakhi cuisine is a rich blend of Tibetan, central Asian, and Indian influences. The staple foods 
                                    of Ladakh are Thukpa, momos, skyu, chutagi, Butter tea known as  (Gur Gur Chai),(salty tea made of butter 
                                    and Yak milk), Khambir, Chhurpi, and Apricot products like juices, jams, and dried fruits.
                                </p>
                                <p class="pera">
