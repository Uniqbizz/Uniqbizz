                                    of the monastery features intricate paintings, ancient statues, prayer halls, and Buddha scriptures, 
                                    offering a glimpse into the rich heritage of Ladakh.
                                </p>
                                <p class="pera">
                                    The Losar festival of Ladakh is an event where family and friends come together wearing new clothes 
                                    celebrate with traditional rituals to mark a new beginning. Other festivals like the Hemis Tse Chu 
