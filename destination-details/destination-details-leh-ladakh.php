                                    of the Changthangi goats, intricate woodcarvings, and handwoven rugs. Perak is a traditional dress, 
                                    made of leather or cotton strap, studded meticulously with large turquoise stones. It is worn by 
                                    the married women of the region.The Women of Ladakh also adorn themselves with intricate jewellery 
                                    made of silver, coral and other precious stones. The Tipi is a hat worn by both men and women.
